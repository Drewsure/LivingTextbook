export function filterAiGenerationRequestPacketPreviewsByTenant(
  packets: AiGenerationRequestPacketPreview[],
  tenantId: string,
): AiGenerationRequestPacketPreview[] {
  return packets.filter((packet) => packet.tenantId === tenantId);
}
